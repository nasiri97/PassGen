import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction

abstract class SyncIosVersionTask : DefaultTask() {

    @get:Input abstract val fullName: Property<String>
    @get:Input abstract val core: Property<String>
    @get:Input abstract val code: Property<Int>
    @get:OutputFile abstract val xcconfig: RegularFileProperty

    @TaskAction
    fun sync() {
        val file = xcconfig.get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            // GENERATED by ./gradlew syncIosVersion. Do not edit.
            // Source version: ${fullName.get()}
            MARKETING_VERSION=${core.get()}
            CURRENT_PROJECT_VERSION=${code.get()}
            """.trimIndent() + "\n"
        )
    }
}