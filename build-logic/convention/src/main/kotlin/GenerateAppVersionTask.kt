import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates:
 *
 *   package <packageName>
 *   object AppVersion { const val NAME: String; const val CODE: Int }
 *
 * into <outputDir>/<package as folders>/AppVersion.kt
 */
@CacheableTask
abstract class GenerateAppVersionTask : DefaultTask() {

    @get:Input
    abstract val versionName: Property<String>
    @get:Input
    abstract val versionCode: Property<Int>
    @get:Input
    abstract val packageName: Property<String>
    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val dir = outputDir.get().asFile.resolve(pkg.replace('.', '/'))
        dir.mkdirs()
        dir.resolve("AppVersion.kt").writeText(
            """
            package $pkg

            /** GENERATED by the app.version plugin from gradle.properties. DO NOT EDIT. */
            object AppVersion {
                const val NAME: String = "${versionName.get()}"
                const val CODE: Int = ${versionCode.get()}
            }
            """.trimIndent() + "\n"
        )
    }
}
